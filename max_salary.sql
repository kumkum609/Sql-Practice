use office;
show tables;
select * from employees;

with MAX_SALARY AS (
	SELECT DEPT, MAX(SALARY) AS MAX_SALARY 
    FROM EMPLOYEES
    GROUP BY DEPT
) 
SELECT E.EMP_ID,E.FNAME,E.DEPT,E.SALARY,A.MAX_SALARY
FROM EMPLOYEES E
JOIN MAX_SALARY A
ON E.DEPT = A.DEPT
WHERE  E.SALARY = A.MAX_SALARY 
LIMIT 1;
